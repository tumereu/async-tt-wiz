package arcanum.parser

/** Regular expressions of the Gatecrash (gtc) and Dragon's Maze (dgm) wordings read in [Sentences]. */
internal object Gtc {
    // gtc chunk 01: "[subject] gain(s) …/get(s) …/can't … until end of turn and … this turn."
    val TIMED_PREDICATES = Regex("""(.+?) ((?:gains?|gets?|can't|loses?) .+ (?:until end of turn|this turn))\.""")
    val PREDICATE_AND = Regex(""",? and (?=(?:gains?|gets?|can't|loses?) )""")
    val TIMING = Regex("""(.+?) (until end of turn|this turn)""")
    val GAIN_KEYWORDS = Regex("""gains? (.+)""")
    val GET_PT = Regex("""gets? ([+-](?:\d+|X))/([+-](?:\d+|X))""")
    val CANT_BE_BLOCKED_BY = Regex("""can't be blocked by (.+)""")

    // one-shot effects
    val REGENERATE = Regex("""Regenerate (.+)\.""")
    val PREVENT_ALL_DAMAGE_TO = Regex("""Prevent all (combat )?damage that would be dealt to (.+) this turn\.""")
    val PREVENT_ALL_COMBAT_DAMAGE_BY = Regex("""Prevent all combat damage that would be dealt this turn by (.+)\.""")
    val RETURN_ALL_TO_HAND = Regex("""Return all (.+) to their owners?'s? hands?\.""")
    val EXILE_ALL = Regex("""Exile all (.+)\.""")
    val DRAW_CARDS_EQUAL_TO = Regex("""Draw cards equal to (.+)\.""")
    val TAP_X_TARGETS = Regex("""Tap X target (.+)\.""")
    val DOESNT_UNTAP_NEXT = Regex("""(That creature|It|Those creatures|They) (?:doesn't|don't) untap during (?:its|their) controller's next untap step\.""")
    val CONTROLLER_CREATES = Regex("""(?:That creature's|Its) controller creates (.+)\.""")
    val MOVE_COUNTER = Regex("""Move (a|an|one|two) (\S+) counters? from (.+) onto (.+)\.""")
    val PUT_ON_TOP = Regex("""Put (target .+) on top of its owner's library\.""")
    val REVEAL_UNTIL_INTO_GRAVEYARD = Regex("""(Target player|target player|Each opponent|each opponent|That player|that player) reveals cards from the top of their library until they reveal (a|an|X|two|three|four|five) (.+?) cards?, then puts (?:those cards|all cards revealed this way) into their graveyard\.""")
    val ITS_CONTROLLER_LOSES = Regex("""Its controller loses (\d+) life\.""")
    val ADD_ADDITIONAL = Regex("""Add an additional (\{.\})\.""")
    val TARGET_PLAYER_SACRIFICES = Regex("""Target player sacrifices (.+?) of their choice(?:, then gains life equal to that creature's (toughness))?\.""")
    val ITS_CONTROLLER_MILLS_EQUAL = Regex("""Its controller mills cards equal to that creature's (power|toughness)\.""")
    val EXILE_TOP_THEN_PUT_ONTO_BATTLEFIELD = Regex("""Exile the top (\w+) cards of (that player's|your) library, then put an? (.+?) card from among them onto the battlefield under your control\.""")
    val REMOVE_A_COUNTER_FROM = Regex("""Remove a counter from (target .+)\.""")
    val PLAYER_ACTIONS = Regex("""(Target player) ((?:[^,]+, )+)then (.+)\.""")
    val UNTAP_THAT = Regex("""Untap (that creature|those creatures)\.""")
    val DEALS_N_DAMAGE = Regex("""(.+?) deals (\d+|X) damage to (.+)\.""")
    val DEALS_DAMAGE_TO_EQUAL = Regex("""(.+?) deals damage to (.+?) equal to (.+)\.""")
    val DEALS_DAMAGE_SAME_NAME = Regex("""(.+?) deals (\d+) damage to target (.+?) and each other (.+?) with the same name as that \w+\.""")
    val GAIN_CONTROL_OF_ALL = Regex("""Gain control of all (.+)\.""")
    val BLOCKS_IF_ABLE = Regex("""(Target .+?) blocks this turn if able\.""")
    val PUT_COUNTER_AND_UNTAP = Regex("""Put an? (\S+) counter on (target .+?) and untap it\.""")
    val PUT_COUNTER_ON_ATTACHED = Regex("""Put an? (\S+) counter on enchanted creature\.""")
    val CHOOSE_TARGET = Regex("""Choose target (.+)\.""")
    val GAIN_LIFE_POWER_PLUS_TOUGHNESS = Regex("""You gain life equal to that creature's power plus its toughness\.""")

    val REVEALS_THAT_MANY_FROM_HAND = Regex("""Target opponent reveals that many cards from their hand\.""")
    val THIS_TURN_ENTERS_WITH_ADDITIONAL = Regex("""This turn, each (.+) enters with an additional (\S+) counter on it\.""")
    val MOVE_ANY_NUMBER_OF_COUNTERS = Regex("""Move any number of (\S+) counters from target (.+?) onto another target (.+?) with the same controller\.""")
    val REMOVE_COUNTERS_COST = Regex("""Remove (a|an|one|two|three|four|five|six|one or more) (\S+) counters? from (.+)""")
    val ADD_MANA_FOR_EACH_COUNTER = Regex("""Add (\{.\} for each \S+ counter on .+)\.""")
    val MANA_FOR_EACH_COUNTER = Regex("""(\{.\}) for each (\S+) counter on (.+)""")

    val STILL_A = Regex("""(?:It's|He's|She's) still an? (?:land|planeswalker|artifact)\.""")
    val CHOOSE_KEYWORD = Regex("""Choose ([a-z ]+(?:, [a-z ]+)*,? or [a-z ]+)\.""")
    val GAIN_THAT_ABILITY = Regex("""(.+) gain that ability until end of turn\.""")
    val BECOMES = Regex("""(Until end of turn, )?(.+?) becomes (an? .+?)(?: and gains (.+?))?( until end of turn)?( and can't be blocked this turn)?\.""")
    val BECOMES_DESCRIPTION = Regex("""an? (?:(\d+)/(\d+) )?(?:((?:white|blue|black|red|green)(?: and (?:white|blue|black|red|green))?) )?((?:[A-Z][a-z]+ )*)(artifact creature|creature)(?: with (.+))?""")
    val PT_EACH_EQUAL = Regex("""power and toughness each equal to (.+)""")
    val COUNTERS_ON_SELF = Regex("""the number of (\S+) counters on (?:him|her|it|this creature|this permanent)""")
    val PUT_COUNTER_FOR_EACH = Regex("""Put an? (\S+) counter on (.+?) for each (.+)\.""")
    val TARGET_OPPONENT_CONTROLS = Regex("""(.+) target opponent controls""")
    val FOR_EACH_OPPONENT = Regex("""For each opponent, (.+)""")
    val PRIMORDIAL_EXILE_GAIN_LIFE = Regex("""exile up to one target (.+?) that player controls and that player gains life equal to its power\.""")
    val PRIMORDIAL_CAST = Regex("""you may cast up to one target (.+?) from that player's graveyard without paying its mana cost\.""")
    val PRIMORDIAL_PUT_ONTO_BATTLEFIELD = Regex("""you may put up to one target (.+?) from that player's graveyard onto the battlefield under your control\.""")
    val PRIMORDIAL_GAIN_CONTROL = Regex("""gain control of up to one target (.+?) that player controls until end of turn\.""")
    val PRIMORDIAL_DESTROY = Regex("""destroy target (.+?) that player controls\.""")
    val SEARCH_UP_TO_X_DESTROYED = Regex("""Search your library for up to X (.+?) cards?, where X is the number of permanents destroyed this way, put those cards onto the battlefield tapped, then shuffle\.""")

    val YOUR_NTH_SPELL_EACH_TURN = Regex("""you cast your (\w+) spell each turn""")
    val GETS_FOR_EACH_BLOCKED = Regex("""It gets \+(\d+)/\+(\d+) until end of turn for each creature it's blocking\.""")

    val SHUFFLE_SELF_AND_TARGETS = Regex("""Shuffle (.+?) and up to (\w+) target (.+?) from a single graveyard into their owners' libraries\.""")

    val PLAYERS_DEALT_DAMAGE_CANT_CAST = Regex("""Players dealt damage this way can't cast (.+?) spells this turn\.""")
    val RETURN_A_CARD_EXILED_WITH = Regex("""Return a card exiled with (.+) to its owner's hand\.""")
    val PUT_REVEALED_INTO_HAND_REST_GRAVEYARD = Regex("""Put all (.+?) cards revealed this way into your hand and the rest into your graveyard\.""")
    val SELF_GAINS_PROTECTION_OF_CHOICE = Regex("""(.+) gains protection from the color of your choice until end of turn\.""")
    val IT_HAS_QUOTED = Regex("""It has "(.+)"\.?""")
    val RETURN_A_CARD_NAMED = Regex("""Return a card named (.+) from your graveyard to the battlefield\.""")
    val LOOK_AT_TOP_OF_TARGET_PLAYERS = Regex("""Look at the top (\w+) cards of target player's library\. Put one back and the rest into that player's graveyard\.""")
    val RETURN_THEN_THAT_PLAYER_DISCARDS = Regex("""Return target (.+?) to its owner's hand, then that player discards a card\.""")
    val IF_ITS_A_MAY_REVEAL_INTO_HAND = Regex("""If it's an? (.+?), you may reveal it and put it into your hand\.""")
    val FIGHTS_ANOTHER_TARGET = Regex("""Target (.+?) fights another target (.+)\.""")
    val THAT_CREATURE_FIGHTS_TARGET = Regex("""That creature fights target (.+)\.""")
    val WHENEVER_THIS_TURN = Regex("""Whenever (.+?) this turn, (.+)""")
    val MAY_BECOME_COPY_EXCEPT = Regex("""You may have (.+?) become a copy of that card, except (.+)\.""")
    val BECOMES_COPY_OF_TARGET_EXCEPT = Regex("""(.+?) becomes a copy of target (.+?), except (.+)\.""")
    val CREATE_X_TOKEN_THAT_SPELL = Regex("""(Create an X/X .+? token), where X is that spell's mana value\.""")
    val RETURN_TARGET_AND_AURAS = Regex("""Return target (.+?) and all (.+?) attached to it to their owner's hand\.""")
    val DESTROY_AND_LOSE_LIFE_EQUAL = Regex("""Destroy target (.+?) and you lose life equal to its (power|toughness)\.""")
    val ITS_CONTROLLER_MILLS = Regex("""Its controller mills (\w+) cards\.""")
    val SEARCH_N_AND_REVEAL = Regex("""Search your library for (\w+) (.+?) cards and reveal them\.""")
    val IF_DIFFERENT_NAMES_RANDOM_INTO_HAND = Regex("""If you reveal (\w+) cards with different names, choose one of them at random and put that card into your hand\.""")
    val AURAS_CONTROLLER_SACRIFICES_DRAWS = Regex("""(.+?)'s controller sacrifices it, then draws (\w+) cards\.""")
    val IF_ITS_A_MAY_CAST_FREE = Regex("""If it's an? (.+?), you may cast it without paying its mana cost\.""")
    val IF_ITS_A_MAY_PUT_AND_RETURN_SELF = Regex("""If it's an? (.+?), you may put it onto the battlefield and return (.+?) to its owner's hand\.""")
    val HAVE_BASE_PT_UNTIL_EOT = Regex("""(.+) have base power and toughness (X|\d+)/(X|\d+) until end of turn\.""")
    val DEALS_THAT_MUCH_DAMAGE = Regex("""(.+?) deals that much damage to (.+)\.""")
    val DRAW_FOR_EACH_MILLED = Regex("""You draw a card for each (.+?) card put into their graveyard this way\.""")
    val EXCEPT_NAME_IS = Regex("""its name is (.+?), (?=it's|and it has|it has)""")
    val EXCEPT_IT_HAS = Regex("""(?:and )?it has (.+)$""")

    val LOSES_THAT_MUCH_LIFE = Regex("""(Each opponent|Target player|You) loses? that much life\.""")
    val MAY_EXILE_RETURN_NEXT_UPKEEP = Regex("""You may exile (.+?)\. If you do, return it to the battlefield under its owner's control at the beginning of your next upkeep\.""")
    val ONLY_OPPONENTS_MAY_ACTIVATE = Regex(""" ?Only your opponents may activate this ability\.""")
    val ABILITY_OF_IS_ACTIVATED_NOT_MANA = Regex("""an ability of (.+) is activated, if it isn't a mana ability""")

    // static abilities
    val OTHERS_ENTER_TAPPED = Regex("""(.+) enter tapped\.""")
    val ENCHANTED_HAS_QUOTED = Regex("""Enchanted (land|creature|permanent|artifact) has "(.+)"""")
    val CAN_BLOCK_ANY_NUMBER = Regex("""(.+) can block any number of creatures\.""")
    val ARE_THE_CHOSEN_TYPE = Regex("""(.+) are the chosen type in addition to their other types\.""")
    val AS_ENTERS_CHOOSE_BASIC_LAND_TYPE = Regex("""As (.+) enters, choose a basic land type\.""")
    val HAS_PREDICATES = Regex("""(.+?) ((?:has|have|gets?|can't) .+)\.""")
    val STATIC_PREDICATE_AND = Regex(""",? and (?=(?:has|have|gets?|can't|attacks?|its) )""")
    val HAVE_KEYWORDS = Regex("""(?:has|have) (.+)""")
    val GETS_MINUS_X_CONTROLLERS_GRAVEYARD = Regex("""(.+) gets -X/-X, where X is the number of (.+?) cards? in its controller's graveyard\.""")
    val GETS_FOR_EACH = Regex("""(.+) gets \+(\d+)/\+(\d+) for each (.+)\.""")
    val PREVENT_DAMAGE_TO_SELF_BY_BLOCKERS = Regex("""Prevent all combat damage that would be dealt to (.+) by creatures blocking it\.""")
    val BLOCKING_OR_BLOCKED_BY_HAVE = Regex("""Creatures blocking or blocked by (.+) have (.+)\.""")
    val TARGETABLE_DESPITE_HEXPROOF = Regex("""(.+) with hexproof can be the targets of spells and abilities you control as though they didn't have hexproof\.""")
    val MAY_LOOK_AT_EXILED_WITH = Regex("""You may look at cards exiled with (.+)\.""")
    val MAY_PLAY_EXILED_WITH = Regex("""You may play lands and cast spells from among cards exiled with (.+)\.""")
    val ENTERS_WITH_X_COUNTERS = Regex("""(.+) enters with X (\S+) counters on it, where X is (.+)\.""")
    val OTHERS_ENTER_WITH_COUNTERS_EQUAL_AND_AS = Regex("""(Each other .+) enters with a number of additional (\S+) counters on it equal to (.+?) and as an? (\w+) in addition to its other types\.""")
}
