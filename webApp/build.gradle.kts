import groovy.json.JsonOutput
import groovy.json.JsonSlurper
import java.security.MessageDigest

// The web client's page (docs/specs/web-client.md §1 item 1, §11 step 3): the browser entry point, index.html with the
// first load's loading screen, and the build the server serves (§2.1). The app itself is :app-ui's.
//   ./scripts/gradle.sh :webApp:webDist     the served build in build/web (index.html, build, <build id>/...)
// The server serves it from WEB_APP_DIR (set to that folder); without one it serves no web app.
plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.compose.multiplatform)
}

val releaseMetadata = JsonSlurper().parseText(providers.fileContents(
    rootProject.layout.projectDirectory.file("release/version.json")).asText.get()) as Map<*, *>
val allocatedVersion = (releaseMetadata["allocations"] as List<*>).last() as Map<*, *>
val gitCommit = providers.exec { commandLine("git", "rev-parse", "--short=12", "HEAD"); isIgnoreExitValue = true }
    .standardOutput.asText.map { it.trim().takeIf { value -> value.matches(Regex("[0-9a-f]{7,40}")) } ?: "unknown" }.get()
// A release build (step 8) turns the test build's allowances off: problem diagnostics and Switch account (LOB-009).
val webRelease = providers.gradleProperty("atwWebRelease").orElse("false").get().toBooleanStrict()
val catalogChecksum = providers.gradleProperty("atwCatalogChecksum").orElse("").get()
require(catalogChecksum.isEmpty() || Regex("[0-9a-f]{64}").matches(catalogChecksum)) { "atwCatalogChecksum must be a SHA-256" }
val artContact = providers.gradleProperty("atwArtContact").orElse("").get()
require(artContact.length <= 200 && artContact.all { it.code in 32..126 && it != '"' && it != '\\' && it != '$' })

// The build's values as Kotlin (the Android app's BuildConfig fields of the same names; the origin is the page's own).
val buildValues = tasks.register("webBuildValues") {
    val output = layout.buildDirectory.dir("generated/webBuildValues")
    val values = mapOf("VERSION_NAME" to "\"${allocatedVersion["versionName"]}\"", "VERSION_CODE" to "${allocatedVersion["versionCode"]}",
        "GIT_COMMIT" to "\"$gitCommit\"", "RELEASE" to "$webRelease", "CATALOG_CHECKSUM" to "\"$catalogChecksum\"",
        "ART_CONTACT" to "\"$artContact\"")
    inputs.property("values", values)
    outputs.dir(output)
    doLast {
        val file = output.get().file("org/asyncttwiz/web/WebBuildValues.kt").asFile
        file.parentFile.mkdirs()
        file.writeText("package org.asyncttwiz.web\n\n/** Generated by webApp/build.gradle.kts. */\ninternal object WebBuildValues {\n" +
            values.entries.joinToString("") { (name, value) -> "    const val $name = $value\n" } + "}\n")
    }
}

// The files the shared UI reads as bundled files (Android: its assets): the release notes (as the Android app packs them)
// and the set symbol font.
abstract class WebAssets : DefaultTask() {
    @get:InputDirectory @get:PathSensitive(PathSensitivity.RELATIVE) abstract val notes: DirectoryProperty
    @get:InputDirectory @get:PathSensitive(PathSensitivity.RELATIVE) abstract val fonts: DirectoryProperty
    @get:OutputDirectory abstract val outputDirectory: DirectoryProperty
    @TaskAction fun generate() {
        val output = outputDirectory.get().asFile
        output.deleteRecursively()
        output.resolve("fonts").mkdirs()
        val line = Regex("(set|add|mod|fix): (.*)")
        val entries = notes.get().asFile.listFiles().orEmpty().filter { it.name.endsWith(".txt") }.sortedBy { it.name }.map { file ->
            val note = requireNotNull(line.matchEntire(file.readText().trim())) { "Release note ${file.name} is malformed" }
            mapOf("id" to file.name.removeSuffix(".txt"), "kind" to note.groupValues[1], "text" to note.groupValues[2].trim())
        }
        output.resolve("release-notes.json").writeText(JsonOutput.toJson(entries))
        listOf("keyrune.ttf", "keyrune-codes.txt").forEach { fonts.get().asFile.resolve(it).copyTo(output.resolve("fonts/$it")) }
    }
}
val webAssets = tasks.register<WebAssets>("webAssets") {
    notes.set(rootProject.layout.projectDirectory.dir("release/notes"))
    fonts.set(rootProject.layout.projectDirectory.dir("androidApp/src/main/assets/fonts"))
    outputDirectory.set(layout.buildDirectory.dir("generated/webAssets"))
}

kotlin {
    jvmToolchain(21)
    @OptIn(org.jetbrains.kotlin.gradle.ExperimentalWasmDsl::class)
    wasmJs {
        outputModuleName.set("atw")
        browser {
            commonWebpackConfig { outputFileName = "atw.js" }
            testTask { enabled = false }
        }
        binaries.executable()
    }
    sourceSets {
        wasmJsMain {
            kotlin.srcDir(buildValues)
            resources.srcDir(webAssets)
            dependencies {
                implementation(project(":app-ui"))
                implementation(libs.cmp.runtime)
                implementation(libs.cmp.ui)
            }
        }
    }
}

// The served build (§2.1): the production distribution's files under a folder named by their content's hash, so they are
// cached for good, beside index.html (pointing at that folder, never cached) and `build` (the hash: open tabs compare it
// with their own, WEB-006).
val webDist = tasks.register("webDist") {
    group = "build"
    description = "The web client as the server serves it (WEB_APP_DIR)."
    val distribution = tasks.named("wasmJsBrowserDistribution")
    dependsOn(distribution)
    // The engine's Web Worker (engine.js and its wasm), beside the app's files (docs/specs/web-client.md §1 item 3)
    dependsOn(":webApp:engine:wasmJsBrowserDistribution")
    val source = layout.buildDirectory.dir("dist/wasmJs/productionExecutable")
    val engineSource = project(":webApp:engine").layout.buildDirectory.dir("dist/wasmJs/productionExecutable")
    val output = layout.buildDirectory.dir("web")
    inputs.dir(source)
    inputs.dir(engineSource)
    outputs.dir(output)
    doLast {
        fun filesOf(from: File) = from.walkTopDown().filter { it.isFile && it.name != "index.html" }.map { it.relativeTo(from).invariantSeparatorsPath to it }
        val files = (filesOf(source.get().asFile) + filesOf(engineSource.get().asFile)).sortedBy { it.first }.toList()
        check(files.map { it.first }.toSet().size == files.size) { "The app's and the engine worker's files share a name" }
        val digest = MessageDigest.getInstance("SHA-256")
        files.forEach { (path, file) -> digest.update(path.toByteArray()); digest.update(file.readBytes()) }
        val build = digest.digest().joinToString("") { "%02x".format(it) }.take(16)
        val to = output.get().asFile
        to.deleteRecursively()
        val from = source.get().asFile
        files.forEach { (path, file) -> file.copyTo(to.resolve("$build/$path")) }
        to.resolve("index.html").writeText(from.resolve("index.html").readText()
            .replace("%ATW_BASE%", "/web/$build/").replace("%ATW_BUILD%", build))
        to.resolve("build").writeText(build + "\n")
        logger.lifecycle("Web build $build in $to")
    }
}
